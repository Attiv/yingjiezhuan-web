import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const root = new URL('../dist/', import.meta.url);
const dist = root.pathname;
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else if (entry.isFile() && entry.name !== 'sw.js') files.push(path);
  }
  return files;
}

const files = (await walk(dist)).sort();
if (!files.some((path) => relative(dist, path) === 'index.html')) throw new Error('dist/index.html is missing; run the Vite build first.');
const hash = createHash('sha256');
for (const path of files) {
  hash.update(relative(dist, path));
  hash.update(await readFile(path));
}
const version = hash.digest('hex').slice(0, 16);
const precache = files.map((path) => `/${relative(dist, path).split(sep).map(encodeURIComponent).join('/')}`);
const source = `/* Generated by scripts/generate-pwa.mjs; edit the generator, not dist/sw.js. */
const CACHE_NAME = 'yingjiezhuan-${version}';
const PRECACHE_URLS = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_URLS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys
    .filter((key) => key.startsWith('yingjiezhuan-') && key !== CACHE_NAME)
    .map((key) => caches.delete(key)))).then(() => self.clients.claim()));
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).then((response) => {
      if (response.ok) caches.open(CACHE_NAME).then((cache) => cache.put('/index.html', response.clone()));
      return response;
    }).catch(async () => (await caches.match('/index.html')) || Response.error()));
    return;
  }

  event.respondWith(caches.open(CACHE_NAME).then(async (cache) => {
    const cached = await cache.match(request, { ignoreSearch: true });
    if (cached) return cached;
    const response = await fetch(request);
    if (response.ok) await cache.put(request, response.clone());
    return response;
  }).catch(() => Response.error()));
});
`;
await writeFile(join(dist, 'sw.js'), source, 'utf8');
console.log(`PWA service worker generated: ${files.length} files, ${version}`);
